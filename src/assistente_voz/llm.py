# ── data contracts ─────────────────────────────────────────────────────────────


@dataclass(frozen=True)
class LLMResponse:
    text: str
    model: str
    latency_ms: float
    provider: str = ""
    time_to_first_token_ms: float = 0.0


# ── LLM backend interface (injectable) ────────────────────────────────────────


@runtime_checkable
class LLMBackend(Protocol):
    provider_name: str

    def complete(self, messages: list[dict]) -> tuple[str, str, str]:
        """Return (response_text, model_name, provider_name)."""
        ...


class LLMTechnicalError(Exception):
    """Technical availability error that can trigger configured fallback."""


class LLMErrorCode:
    """Stable codes for LLM error classification (Issue 23)."""

    UNAVAILABLE = "LLM_ERR_UNAVAILABLE"
    # Connection refused, timeout, server 5xx — eligible for retry and fallback.

    LOGICAL = "LLM_ERR_LOGICAL"
    # Bad request, auth failure, invalid payload — do NOT retry or fallback.


# ── OpenAI production backend ─────────────────────────────────────────────────


class OpenAIBackend:
    """Production backend using openai SDK."""

    provider_name = "openai"

    def __init__(self, api_key: str, model: str = "gpt-4o") -> None:
        self._model = model
        self._api_key = api_key
        self._client = None

    def _get_client(self):
        if self._client is None:
            from openai import OpenAI  # deferred import

            self._client = OpenAI(api_key=self._api_key)
        return self._client

    def complete(self, messages: list[dict]) -> tuple[str, str, str]:
        client = self._get_client()
        response = client.chat.completions.create(
            model=self._model,
            messages=messages,
        )
        text = response.choices[0].message.content or ""
        return text, response.model, self.provider_name

    def stream(self, messages: list[dict]) -> Iterator[str]:
        """Yield text tokens as they are generated by the model."""
        client = self._get_client()
        with client.chat.completions.create(
            model=self._model,
            messages=messages,
            stream=True,
        ) as streaming_response:
            for chunk in streaming_response:
                delta = chunk.choices[0].delta.content if chunk.choices else None
                if delta:
                    yield delta


class GeminiBackend:
    """Production backend using Google Gemini SDK."""

    provider_name = "gemini"

    def __init__(self, api_key: str, model: str = "gemini-2.0-flash") -> None:
        self._api_key = api_key
        self._model = model
        self._client = None

    def _get_client(self):
        if self._client is None:
            from google import genai  # deferred import

            self._client = genai.Client(api_key=self._api_key)
        return self._client

    def _messages_to_prompt(self, messages: list[dict]) -> str:
        lines: list[str] = []
        for msg in messages:
            role = str(msg.get("role", "user")).upper()
            content = str(msg.get("content", ""))
            lines.append(f"[{role}] {content}")
        return "\n\n".join(lines)

    def complete(self, messages: list[dict]) -> tuple[str, str, str]:
        client = self._get_client()
        prompt = self._messages_to_prompt(messages)
        response = client.models.generate_content(
            model=self._model,
            contents=prompt,
        )
        text = getattr(response, "text", "") or ""
        model_name = getattr(response, "model", None) or self._model
        return text, model_name, self.provider_name

    def stream(self, messages: list[dict]) -> Iterator[str]:
        """Yield text tokens as they are generated by the model."""
        client = self._get_client()
        prompt = self._messages_to_prompt(messages)
        for chunk in client.models.generate_content_stream(
            model=self._model,
            contents=prompt,
        ):
            token = getattr(chunk, "text", None)
            if token:
                yield token


class OllamaBackend:
    """Production backend using local Ollama HTTP API."""

    provider_name = "ollama"

    def __init__(
        self,
        base_url: str = "http://localhost:11434",
        model: str = "qwen2.5:3b",
        timeout_s: float = 30.0,
    ) -> None:
        self._base_url = base_url.rstrip("/")
        self._model = model
        self._timeout_s = timeout_s

    def complete(self, messages: list[dict]) -> tuple[str, str, str]:
        url = f"{self._base_url}/api/chat"
        payload = {
            "model": self._model,
            "messages": messages,
            "stream": False,
        }
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=body,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self._timeout_s) as response:  # noqa: S310
                raw = response.read().decode("utf-8")
        except urllib.error.HTTPError as exc:
            # Availability-related HTTP failures should be eligible for fallback.
            if exc.code in {404, 408, 429, 500, 502, 503, 504}:
                raise LLMTechnicalError(f"Ollama HTTP {exc.code}") from exc
            raise
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            raise LLMTechnicalError("Ollama unavailable") from exc

        data = json.loads(raw or "{}")
        message = data.get("message") or {}
        text = str(message.get("content") or "")
        model_name = str(data.get("model") or self._model)
        return text, model_name, self.provider_name

    def stream(self, messages: list[dict]) -> Iterator[str]:
        """Yield text tokens line-by-line from Ollama's streaming API."""
        url = f"{self._base_url}/api/chat"
        payload = {
            "model": self._model,
            "messages": messages,
            "stream": True,
        }
        body = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=body,
            headers={"Content-Type": "application/json"},
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=self._timeout_s) as response:  # noqa: S310
                while True:
                    raw_line = response.readline()
                    if not raw_line:
                        break
                    line = raw_line.decode("utf-8").strip()
                    if not line:
                        continue
                    try:
                        data = json.loads(line)
                    except json.JSONDecodeError:
                        continue
                    message = data.get("message") or {}
                    token = message.get("content", "")
                    if token:
                        yield token
                    if data.get("done"):
                        break
        except urllib.error.HTTPError as exc:
            if exc.code in {404, 408, 429, 500, 502, 503, 504}:
                raise LLMTechnicalError(f"Ollama HTTP {exc.code}") from exc
            raise
        except (urllib.error.URLError, TimeoutError, OSError) as exc:
            raise LLMTechnicalError("Ollama unavailable") from exc


class FallbackBackend:
    """Try primary backend first; use fallback only for technical errors."""

    provider_name = "fallback"

    def __init__(
        self,
        primary: LLMBackend,
        fallback: LLMBackend,
        enabled: bool,
        notify_fallback: bool,
    ) -> None:
        self._primary = primary
        self._fallback = fallback
        self._enabled = enabled
        self._notify_fallback = notify_fallback

    def complete(self, messages: list[dict]) -> tuple[str, str, str]:
        try:
            return self._primary.complete(messages)
        except Exception as exc:  # noqa: BLE001
            error_code = _classify_error(exc)
            _logger.debug(
                "LLM primary %s failed: code=%s exc=%s",
                self._primary.provider_name, error_code, type(exc).__name__,
            )
            if not self._enabled or error_code != LLMErrorCode.UNAVAILABLE:
                raise
            if self._notify_fallback:
                _logger.warning(
                    "LLM fallback: %s -> %s [%s: %s]",
                    self._primary.provider_name,
                    self._fallback.provider_name,
                    error_code,
                    type(exc).__name__,
                )
            else:
                _logger.info(
                    "LLM fallback: %s -> %s [%s]",
                    self._primary.provider_name,
                    self._fallback.provider_name,
                    error_code,
                )
            return self._fallback.complete(messages)

    def stream(self, messages: list[dict]) -> Iterator[str]:
        primary_stream = getattr(self._primary, "stream", None)
        if primary_stream is None or not callable(primary_stream):
            text, _, _ = self.complete(messages)
            yield text
            return

        started = False
        try:
            for token in primary_stream(messages):
                started = True
                yield token
        except Exception as exc:  # noqa: BLE001
            if started:
                raise  # mid-stream failure: cannot safely recover
            error_code = _classify_error(exc)
            _logger.debug(
                "LLM primary stream %s failed before first token: code=%s exc=%s",
                self._primary.provider_name, error_code, type(exc).__name__,
            )
            if not self._enabled or error_code != LLMErrorCode.UNAVAILABLE:
                raise
            if self._notify_fallback:
                _logger.warning(
                    "LLM streaming fallback: %s -> %s [%s: %s]",
                    self._primary.provider_name,
                    self._fallback.provider_name,
                    error_code,
                    type(exc).__name__,
                )
            else:
                _logger.info(
                    "LLM streaming fallback: %s -> %s [%s]",
                    self._primary.provider_name,
                    self._fallback.provider_name,
                    error_code,
                )
            fallback_stream = getattr(self._fallback, "stream", None)
            if fallback_stream is not None and callable(fallback_stream):
                yield from fallback_stream(messages)
            else:
                text, _, _ = self._fallback.complete(messages)
                yield text


def _get_http_status(exc: Exception) -> int | None:
    """Extract HTTP status code from an exception, regardless of SDK."""
    if isinstance(exc, urllib.error.HTTPError):
        return exc.code
    status = getattr(exc, "status_code", None)
    if isinstance(status, int):
        return status
    response = getattr(exc, "response", None)
    if response is not None:
        code = getattr(response, "status_code", None)
        if isinstance(code, int):
            return code
    return None


# HTTP status codes that signal transient server unavailability.
_UNAVAILABLE_HTTP_CODES = {408, 429, 500, 502, 503, 504}
# HTTP status codes that signal a logical/client error — no retry or fallback.
# 404 is intentionally absent: "model not found" on Ollama is a technical error
# and is already converted to LLMTechnicalError by OllamaBackend before reaching
# this classifier. Keeping 404 out of both sets lets provider-specific handling
# (LLMTechnicalError or SDK exception types) decide its semantics.
_LOGICAL_HTTP_CODES = {400, 401, 403, 422}


def _classify_error(exc: Exception) -> str:
    """Return a stable LLMErrorCode for *exc*.

    UNAVAILABLE  — transient availability failure; eligible for retry and fallback.
    LOGICAL      — bad request, auth, or invalid payload; do not retry or fallback.

    Defaults to LOGICAL when the error type is unknown to avoid masking bugs.
    """
    # Explicitly tagged by a backend
    if isinstance(exc, LLMTechnicalError):
        return LLMErrorCode.UNAVAILABLE

    # Network-level errors — always transient, provider-agnostic
    if isinstance(exc, (ConnectionError, TimeoutError)):
        return LLMErrorCode.UNAVAILABLE
    if isinstance(exc, urllib.error.URLError) and not isinstance(exc, urllib.error.HTTPError):
        return LLMErrorCode.UNAVAILABLE

    # HTTP status classification — works for urllib and any SDK that sets status_code
    status = _get_http_status(exc)
    if status is not None:
        if status in _UNAVAILABLE_HTTP_CODES:
            return LLMErrorCode.UNAVAILABLE
        if status in _LOGICAL_HTTP_CODES:
            return LLMErrorCode.LOGICAL

    # OpenAI SDK (deferred to avoid hard dependency)
    try:
        import openai
        if isinstance(exc, (openai.APIConnectionError, openai.APITimeoutError)):
            return LLMErrorCode.UNAVAILABLE
        if isinstance(exc, openai.APIStatusError):
            if exc.status_code in _UNAVAILABLE_HTTP_CODES:
                return LLMErrorCode.UNAVAILABLE
            return LLMErrorCode.LOGICAL
    except ImportError:
        pass

    # Unknown — assume logical so unexpected exceptions surface as bugs
    return LLMErrorCode.LOGICAL


def _env_bool(name: str, default: bool = False) -> bool:
    raw = os.getenv(name)
    if raw is None:
        return default
    return raw.strip().lower() in {"1", "true", "yes", "on"}


def _compute_backoff(retry_number: int, base_s: float, max_s: float) -> float:
    """Return sleep duration for *retry_number* (1-indexed) with exponential backoff and jitter.

    Formula: min(max_s, base_s * 2^(retry_number-1) +/- 20% jitter).
    Cap is applied AFTER jitter so the result never exceeds max_s.
    retry_number=1 → ~base_s, retry_number=2 → ~2*base_s, etc.
    """
    raw_delay = base_s * (2.0 ** (retry_number - 1))
    jitter = raw_delay * random.uniform(-0.2, 0.2)
    return max(0.0, min(max_s, raw_delay + jitter))


def _should_notify_fallback() -> bool:
    env = os.getenv("APP_ENV", "dev").strip().lower()
    if env not in {"dev", "development", "local"}:
        return False
    return _env_bool("LLM_NOTIFY_FALLBACK", default=False)


# ── system prompt builder ─────────────────────────────────────────────────────


def build_system_prompt(profile_data: dict) -> str:
    """Derive a system prompt from a loaded profile's YAML data."""
    profile = profile_data.get("profile", {})
    description = profile.get("description", "")
    name = profile.get("name", profile.get("id", "assistant"))

    lines: list[str] = [
        f"Você é {name}. {description}".strip(),
        "",
    ]

    # output contract sections → guardrails
    output_contract = profile_data.get("output_contract", {})
    required_sections = output_contract.get("required_sections", [])
    if required_sections:
        lines.append("Suas respostas devem sempre incluir as seguintes seções:")
        for sec in required_sections:
            lines.append(f"  - {sec.replace('_', ' ').capitalize()}")
        lines.append("")

    # anamnesis rules
    anamnesis = profile_data.get("anamnesis", {})
    required_fields = anamnesis.get("required_fields", [])
    max_q = anamnesis.get("max_questions_per_cycle")
    if required_fields:
        lines.append("Campos obrigatórios a coletar na anamnese:")
        for f in required_fields:
            lines.append(f"  - {f.replace('_', ' ')}")
        lines.append("")
    if max_q:
        lines.append(f"Faça no máximo {max_q} perguntas por ciclo de interação.")
        lines.append("")

    # interview rules
    interview = profile_data.get("interview", {})
    seniority_weights = interview.get("seniority_weights", {})
    if seniority_weights:
        lines.append("Pesos de avaliação por senioridade estão configurados no perfil.")
        lines.append("")

    # safety / red flags
    stt_cfg = profile_data.get("stt", {})
    if stt_cfg.get("block_llm_below_threshold"):
        lines.append(
            "Nunca prossiga com informação cuja transcrição não foi confirmada."
        )
        lines.append("")

    # generic extra instructions from profile
    instructions = profile_data.get("instructions", "")
    if instructions:
        lines.append(instructions.strip())
        lines.append("")

    return "\n".join(lines).strip()


# ── LLM service ────────────────────────────────────────────────────────────────


class LLMService:
    """Send conversation history to the LLM using the active profile's prompt.

    Usage::

        svc = LLMService(backend=OpenAIBackend(api_key="..."), profile_data={...})
        svc.apply_profile(state)        # sets system message from profile
        response = svc.complete(state)  # sends history, returns LLMResponse
    """

    def __init__(
        self,
        backend: LLMBackend,
        profile_data: dict,
        max_retries: int = 2,
        backoff_base_s: float = 1.0,
        backoff_max_s: float = 10.0,
    ) -> None:
        self._backend = backend
        self._profile_data = profile_data
        self._max_retries = max_retries
        self._backoff_base_s = backoff_base_s
        self._backoff_max_s = backoff_max_s

    def apply_profile(self, state: ConversationState) -> None:
        """Inject the profile's system prompt into *state*."""
        system_prompt = build_system_prompt(self._profile_data)
        state.set_system(system_prompt)

    def complete(self, state: ConversationState) -> LLMResponse:
        """Call the LLM with the current conversation history.

        Retries only on LLM_ERR_UNAVAILABLE up to ``max_retries`` times using
        exponential backoff with jitter (base=backoff_base_s, cap=backoff_max_s).
        Logical errors (LLM_ERR_LOGICAL) are raised immediately without retry.
        Raises the last exception if all retries fail.
        """
        messages = state.to_llm_messages()
        last_exc: Exception | None = None
        total_attempts = self._max_retries + 1

        for attempt in range(1, total_attempts + 1):
            t0 = time.perf_counter()
            try:
                text, model, provider = self._backend.complete(messages)
                latency_ms = (time.perf_counter() - t0) * 1000
                return LLMResponse(text=text, model=model, latency_ms=latency_ms, provider=provider)
            except Exception as exc:  # noqa: BLE001
                error_code = _classify_error(exc)
                last_exc = exc
                if error_code == LLMErrorCode.LOGICAL:
                    _logger.warning(
                        "LLM attempt %d/%d failed: code=%s exc=%s — not retriable",
                        attempt, total_attempts, error_code, type(exc).__name__,
                    )
                    break
                if attempt < total_attempts:
                    sleep_s = _compute_backoff(attempt, self._backoff_base_s, self._backoff_max_s)
                    _logger.warning(
                        "LLM attempt %d/%d failed: code=%s exc=%s — retry in %.2fs",
                        attempt, total_attempts, error_code, type(exc).__name__, sleep_s,
                    )
                    time.sleep(sleep_s)
                else:
                    _logger.warning(
                        "LLM attempt %d/%d failed: code=%s exc=%s — retries exhausted",
                        attempt, total_attempts, error_code, type(exc).__name__,
                    )

        raise last_exc  # type: ignore[misc]

    def stream(
        self,
        state: ConversationState,
        on_token: Callable[[str], None],
    ) -> LLMResponse:
        """Call the LLM in streaming mode, invoking *on_token* for each partial token.

        If the backend does not implement ``stream()``, falls back to ``complete()``
        transparently (no ``on_token`` calls in fallback mode).

        Returns an :class:`LLMResponse` with the full accumulated text and
        ``time_to_first_token_ms`` populated when streaming was used.
        """
        messages = state.to_llm_messages()
        backend_stream = getattr(self._backend, "stream", None)

        if backend_stream is None or not callable(backend_stream):
            # Backend does not support streaming — fall back to complete().
            return self.complete(state)

        t0 = time.perf_counter()
        ttft_ms: float = 0.0
        tokens: list[str] = []
        first_token = True

        try:
            for token in backend_stream(messages):
                if first_token:
                    ttft_ms = (time.perf_counter() - t0) * 1000
                    first_token = False
                tokens.append(token)
                on_token(token)
        except (AttributeError, NotImplementedError):
            # stream() exists but raised NotImplementedError — fall back.
            return self.complete(state)

        latency_ms = (time.perf_counter() - t0) * 1000
        full_text = "".join(tokens)
        model = getattr(self._backend, "_model", "") or self._backend.provider_name
        provider = self._backend.provider_name
        return LLMResponse(
            text=full_text,
            model=model,
            latency_ms=latency_ms,
            provider=provider,
            time_to_first_token_ms=ttft_ms,
        )

    # ── factory ───────────────────────────────────────────────────────────────

    @classmethod
    def from_env(cls, profile_data: dict) -> "LLMService":
        """Build LLMService from environment variables.

        LLM_PROVIDER           — api|openai|gemini|ollama
        LLM_FALLBACK_PROVIDER  — openai|gemini|ollama
        LLM_FALLBACK_ENABLED   — 0|1
        LLM_NOTIFY_FALLBACK    — 0|1 (dev/local only)
        LLM_API_KEY            — OpenAI API key (required for openai provider)
        GEMINI_API_KEY         — Gemini API key (required for gemini provider)
        OPENAI_MODEL           — openai model name (default: gpt-4o)
        GEMINI_MODEL           — gemini model name (default: gemini-2.0-flash)
        OLLAMA_MODEL           — ollama model name (default: qwen2.5:3b)
        OLLAMA_BASE_URL        — ollama base url (default: http://localhost:11434)
        OLLAMA_TIMEOUT_S       — ollama timeout in seconds (default: 30)
        LLM_RETRIES            — max retries (default: 2)
        LLM_RETRY_BACKOFF_BASE_S — backoff base in seconds (default: 1.0)
        LLM_RETRY_BACKOFF_MAX_S  — backoff cap in seconds (default: 10.0)
        """
        provider = os.getenv("LLM_PROVIDER", "api").strip().lower()
        max_retries = int(os.getenv("LLM_RETRIES", "2"))
        backoff_base_s = float(os.getenv("LLM_RETRY_BACKOFF_BASE_S", "1.0"))
        backoff_max_s = float(os.getenv("LLM_RETRY_BACKOFF_MAX_S", "10.0"))
        fallback_enabled = _env_bool("LLM_FALLBACK_ENABLED", default=False)
        fallback_provider = os.getenv("LLM_FALLBACK_PROVIDER", "").strip().lower()

        def _build_backend(selected_provider: str) -> LLMBackend:
            if selected_provider in {"api", "openai"}:
                api_key = os.environ["LLM_API_KEY"]
                model = os.getenv("OPENAI_MODEL", os.getenv("LLM_MODEL", "gpt-4o"))
                return OpenAIBackend(api_key=api_key, model=model)
            if selected_provider == "gemini":
                api_key = os.environ["GEMINI_API_KEY"]
                model = os.getenv("GEMINI_MODEL", os.getenv("LLM_MODEL", "gemini-2.0-flash"))
                return GeminiBackend(api_key=api_key, model=model)
            if selected_provider in {"ollama", "local"}:
                base_url = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434")
                model = os.getenv("OLLAMA_MODEL", os.getenv("LLM_MODEL", "qwen2.5:3b"))
                timeout_s = float(os.getenv("OLLAMA_TIMEOUT_S", "30"))
                return OllamaBackend(base_url=base_url, model=model, timeout_s=timeout_s)
            raise ValueError("Unsupported LLM provider. Use: api, openai, gemini, ollama")

        backend: LLMBackend = _build_backend(provider)
        if fallback_enabled and fallback_provider:
            fallback_backend = _build_backend(fallback_provider)
            if fallback_backend.provider_name != backend.provider_name:
                backend = FallbackBackend(
                    primary=backend,
                    fallback=fallback_backend,
                    enabled=True,
                    notify_fallback=_should_notify_fallback(),
                )


        return cls(
            backend=backend,
            profile_data=profile_data,
            max_retries=max_retries,
            backoff_base_s=backoff_base_s,
            backoff_max_s=backoff_max_s,
        )
